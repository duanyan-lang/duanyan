//! SNARjs Firmware Packaging
//!
//! Takes the compiler's machine-code output and packages it into deployable
//! artifacts: Intel HEX, raw binary, and a Gowin Verilog ROM stub.

use std::fs;
use std::path::{Path, PathBuf};

use crate::backend::Instruction;

/// A firmware bundle ready for flashing or simulation.
#[derive(Debug, Clone)]
#[allow(dead_code)]
pub struct FirmwareBundle {
    pub hex_path: PathBuf,
    pub bin_path: PathBuf,
    pub entry_address: u32,
    pub word_count: usize,
}

/// Emit machine code to Intel HEX and raw binary.
pub fn emit_bundle(
    instructions: &[Instruction],
    base_dir: &Path,
    stem: &str,
) -> Result<FirmwareBundle, String> {
    let words: Vec<u32> = instructions.iter().map(|i| i.encode()).collect();

    let hex_path = base_dir.join(format!("{}.hex", stem));
    let bin_path = base_dir.join(format!("{}.bin", stem));

    // Intel HEX-ish plain format: one 32-bit word per line (existing convention).
    let hex_lines: Vec<String> = words.iter().map(|w| format!("{:08X}", w)).collect();
    fs::write(&hex_path, hex_lines.join("\n") + "\n")
        .map_err(|e| format!("写入 hex 失败: {}", e))?;

    // Raw binary: little-endian 32-bit words.
    let mut bin_bytes = Vec::with_capacity(words.len() * 4);
    for w in &words {
        bin_bytes.extend_from_slice(&w.to_le_bytes());
    }
    fs::write(&bin_path, bin_bytes)
        .map_err(|e| format!("写入 bin 失败: {}", e))?;

    Ok(FirmwareBundle {
        hex_path,
        bin_path,
        entry_address: 0,
        word_count: words.len(),
    })
}

/// Emit a Verilog ROM module for direct integration into the FPGA project.
pub fn emit_verilog_rom(
    instructions: &[Instruction],
    path: &Path,
    module_name: &str,
) -> Result<(), String> {
    let words: Vec<String> = instructions
        .iter()
        .map(|i| format!("        32'h{:08X}", i.encode()))
        .collect();
    let depth = words.len().max(1);
    let words_str = words.join(",\n");

    let content = format!(
        "// Auto-generated by SNARjs\n\
         module {NAME} (\n\
             input wire clk,\n\
             input wire [$clog2({DEPTH})-1:0] addr,\n\
             output reg [31:0] data\n\
         );\n\
             always @(posedge clk) begin\n\
                 case (addr)\n{WORDS}\n\
                     default: data = 32'h00000000;\n\
                 endcase\n\
             end\n\
         endmodule\n",
        NAME = module_name,
        DEPTH = depth,
        WORDS = words_str
    );

    fs::write(path, content).map_err(|e| format!("写入 Verilog ROM 失败: {}", e))
}
