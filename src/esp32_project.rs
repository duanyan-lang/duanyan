//! ESP-IDF 项目结构生成模块
//!
//! Phase C: `snar build hello.js --target esp32` 自动生成 ESP-IDF 项目
//! 生成标准 ESP-IDF CMake 项目结构

use std::fs;
use std::path::Path;
use crate::c_codegen::CGenerateResult;

/// 嵌入 C 推理运行时模板 (编译时嵌入)
const SNAR_AI_H_CONTENT: &str = include_str!("ai_runtime/snar_ai.h");
const SNAR_AI_C_CONTENT: &str = include_str!("ai_runtime/snar_ai.c");

/// 生成完整的 ESP-IDF 项目
pub fn generate_esp32_project(
    result: &CGenerateResult,
    output_dir: &Path,
    project_name: &str,
) -> Result<Esp32ProjectPaths, String> {
    let project_dir = output_dir.join("esp32");
    let main_dir = project_dir.join("main");

    fs::create_dir_all(&main_dir)
        .map_err(|e| format!("创建目录失败 {}: {}", main_dir.display(), e))?;

    // 1. 顶层 CMakeLists.txt
    let top_cmake = generate_top_cmake(project_name);
    write_file(&project_dir.join("CMakeLists.txt"), &top_cmake)?;

    // 2. main/CMakeLists.txt
    let main_cmake = generate_main_cmake(result.uses_ai);
    write_file(&main_dir.join("CMakeLists.txt"), &main_cmake)?;

    // 3. main/main.c — 生成的 C 源码
    write_file(&main_dir.join("main.c"), &result.source)?;

    // 4. sdkconfig.defaults
    let sdkconfig = generate_sdkconfig_defaults(result.uses_ai);
    write_file(&project_dir.join("sdkconfig.defaults"), &sdkconfig)?;

    // 5. partitions.csv
    let partitions = generate_partitions_csv();
    write_file(&project_dir.join("partitions.csv"), &partitions)?;

    // 6. Phase F: AI 运行时文件
    let ai_runtime_h = main_dir.join("snar_ai.h");
    let ai_runtime_c = main_dir.join("snar_ai.c");
    if result.uses_ai {
        write_file(&ai_runtime_h, SNAR_AI_H_CONTENT)?;
        write_file(&ai_runtime_c, SNAR_AI_C_CONTENT)?;
    }

    Ok(Esp32ProjectPaths {
        project_dir: project_dir.clone(),
        main_c: main_dir.join("main.c"),
        cmake: project_dir.join("CMakeLists.txt"),
    })
}

/// ESP32 项目输出路径
pub struct Esp32ProjectPaths {
    pub project_dir: std::path::PathBuf,
    pub main_c: std::path::PathBuf,
    pub cmake: std::path::PathBuf,
}

fn write_file(path: &Path, content: &str) -> Result<(), String> {
    fs::write(path, content).map_err(|e| format!("写入文件失败 {}: {}", path.display(), e))
}

fn generate_top_cmake(project_name: &str) -> String {
    format!(
r#"# Auto-generated by SNARjs — ESP-IDF Project
cmake_minimum_required(VERSION 3.16)

include($ENV{{IDF_PATH}}/tools/cmake/project.cmake)
project({project_name})
"#)
}

fn generate_main_cmake(uses_ai: bool) -> String {
    let mut srcs = "\"main.c\"".to_string();
    if uses_ai {
        srcs.push_str(" \"snar_ai.c\"");
    }
    format!(
r#"# Auto-generated by SNARjs — ESP-IDF Main Component
idf_component_register(
    SRCS {srcs}
    INCLUDE_DIRS "."
)
"#)
}

fn generate_sdkconfig_defaults(uses_ai: bool) -> String {
    let mut s = r#"# Auto-generated by SNARjs — ESP32 sdkconfig defaults
CONFIG_ESP32_DEFAULT_CPU_FREQ_240=y
CONFIG_ESP32_DEFAULT_CPU_FREQ_MHZ=240
CONFIG_PARTITION_TABLE_CUSTOM=y
CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y
CONFIG_FREERTOS_HZ=1000
CONFIG_LOG_DEFAULT_LEVEL_WARN=y
"#.to_string();
    if uses_ai {
        s.push_str("\n# Phase F: 千漉Mini AI — PSRAM 配置\n");
        s.push_str("CONFIG_SPIRAM=y\n");
        s.push_str("CONFIG_SPIRAM_USE_MALLOC=y\n");
        s.push_str("CONFIG_SPIRAM_MALLOC_ALWAYSINTERNAL=4096\n");
    }
    s
}

fn generate_partitions_csv() -> String {
    r#"# Auto-generated by SNARjs — ESP32 Partition Table
# Name,   Type, SubType, Offset,   Size,    Flags
nvs,      data, nvs,     0x9000,   0x6000,
phy_init, data, phy,     0xf000,   0x1000,
factory,  app,  factory, 0x10000,  0x1F0000,
"#.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_top_cmake_generation() {
        let cmake = generate_top_cmake("test_project");
        assert!(cmake.contains("cmake_minimum_required"));
        assert!(cmake.contains("project(test_project)"));
        assert!(cmake.contains("IDF_PATH"));
    }

    #[test]
    fn test_main_cmake_generation() {
        let cmake = generate_main_cmake(false);
        assert!(cmake.contains("idf_component_register"));
        assert!(cmake.contains("main.c"));
        assert!(!cmake.contains("snar_ai.c"));
    }

    #[test]
    fn test_main_cmake_with_ai() {
        let cmake = generate_main_cmake(true);
        assert!(cmake.contains("snar_ai.c"));
    }

    #[test]
    fn test_sdkconfig_defaults() {
        let cfg = generate_sdkconfig_defaults(false);
        assert!(cfg.contains("CONFIG_ESP32_DEFAULT_CPU_FREQ_240"));
        assert!(cfg.contains("CONFIG_ESPTOOLPY_FLASHSIZE_4MB"));
        assert!(!cfg.contains("CONFIG_SPIRAM"));
    }

    #[test]
    fn test_sdkconfig_defaults_with_ai() {
        let cfg = generate_sdkconfig_defaults(true);
        assert!(cfg.contains("CONFIG_SPIRAM=y"));
        assert!(cfg.contains("CONFIG_SPIRAM_USE_MALLOC"));
    }

    #[test]
    fn test_ai_runtime_embedded() {
        assert!(SNAR_AI_H_CONTENT.contains("snar_brain_t"));
        assert!(SNAR_AI_C_CONTENT.contains("snar_ai_load_model"));
    }
}
