//! TypeScript 类型定义文件生成器 (.d.ts)
//!
//! 为 DUANYAN 硬件 API 生成完整的 TypeScript 类型定义
//! 供 DUANYAN-IDE 代码补全和类型检查使用

/// 生成 DUANYAN 硬件 API 的完整 .d.ts 文件内容
pub fn generate_dts() -> String {
    let mut dts = String::new();

    dts.push_str("// DUANYAN Hardware API Type Definitions\n");
    dts.push_str("// Auto-generated by DUANYAN compiler\n");
    dts.push_str("// Version: 0.6.0\n\n");

    // GPIO
    dts.push_str("/**\n * GPIO - 通用输入输出\n * COUNPRE64 内存映射: 0x200-0x207\n */\n");
    dts.push_str("declare namespace GPIO {\n");
    dts.push_str("    /** 设置引脚为输出模式 */\n");
    dts.push_str("    function output(pin: number): number;\n");
    dts.push_str("    /** 设置引脚为输入模式 */\n");
    dts.push_str("    function input(pin: number): number;\n");
    dts.push_str("    /** 设置引脚输出高电平 */\n");
    dts.push_str("    function high(pin: number): number;\n");
    dts.push_str("    /** 设置引脚输出低电平 */\n");
    dts.push_str("    function low(pin: number): number;\n");
    dts.push_str("    /** 读取引脚电平 (0=低, 1=高) */\n");
    dts.push_str("    function read(pin: number): number;\n");
    dts.push_str("}\n\n");

    // UART
    dts.push_str("/**\n * UART - 串口通信\n * COUNPRE64 内存映射: 0x100-0x103\n */\n");
    dts.push_str("declare namespace UART {\n");
    dts.push_str("    /** 初始化串口波特率 */\n");
    dts.push_str("    function init(baudRate: number): number;\n");
    dts.push_str("    /** 发送一个字节 (0-255) */\n");
    dts.push_str("    function write(byte: number): number;\n");
    dts.push_str("    /** 读取一个字节 (无数据返回0) */\n");
    dts.push_str("    function read(): number;\n");
    dts.push_str("    /** 发送字符串 */\n");
    dts.push_str("    function print(text: string): void;\n");
    dts.push_str("}\n\n");

    // Timer
    dts.push_str("/**\n * Timer - 硬件定时器\n * COUNPRE64 内存映射: 0x300-0x303\n */\n");
    dts.push_str("declare namespace Timer {\n");
    dts.push_str("    /** 延时指定毫秒 (忙等待) */\n");
    dts.push_str("    function delay(ms: number): number;\n");
    dts.push_str("    /** 启动定时器 */\n");
    dts.push_str("    function start(periodMs: number, oneshot?: boolean): number;\n");
    dts.push_str("    /** 停止定时器 */\n");
    dts.push_str("    function stop(): void;\n");
    dts.push_str("}\n\n");

    // PWM
    dts.push_str("/**\n * PWM - 脉宽调制\n * COUNPRE64 内存映射: 0x400-0x402\n */\n");
    dts.push_str("declare namespace PWM {\n");
    dts.push_str("    /** 设置 PWM 占空比 (duty: 0-255) */\n");
    dts.push_str("    function duty(pin: number, duty: number): number;\n");
    dts.push_str("    /** 配置 PWM 频率 */\n");
    dts.push_str("    function frequency(pin: number, hz: number): number;\n");
    dts.push_str("}\n\n");

    // ADC
    dts.push_str("/**\n * ADC - 模数转换器 (12位, 0-4095)\n * COUNPRE64 内存映射: 0x500-0x502\n */\n");
    dts.push_str("declare namespace ADC {\n");
    dts.push_str("    /** 选择 ADC 通道 */\n");
    dts.push_str("    function channel(ch: number): number;\n");
    dts.push_str("    /** 读取指定通道的 ADC 值 (0-4095) */\n");
    dts.push_str("    function read(channel: number): number;\n");
    dts.push_str("    /** 读取当前选中通道的 ADC 值 */\n");
    dts.push_str("    function read(): number;\n");
    dts.push_str("}\n\n");

    // SPI
    dts.push_str("/**\n * SPI - 串行外设接口\n * COUNPRE64 内存映射: 0x600-0x603\n */\n");
    dts.push_str("declare namespace SPI {\n");
    dts.push_str("    /** 初始化 SPI (时钟频率Hz) */\n");
    dts.push_str("    function init(clockHz: number): number;\n");
    dts.push_str("    /** 发送并接收一个字节 */\n");
    dts.push_str("    function transfer(byte: number): number;\n");
    dts.push_str("}\n\n");

    // I2C
    dts.push_str("/**\n * I2C - 集成电路总线\n * COUNPRE64 内存映射: 0x700-0x703\n */\n");
    dts.push_str("declare namespace I2C {\n");
    dts.push_str("    /** 初始化 I2C (时钟频率Hz) */\n");
    dts.push_str("    function init(clockHz: number): number;\n");
    dts.push_str("    /** 向指定地址写入数据 */\n");
    dts.push_str("    function write(addr: number, data: number): number;\n");
    dts.push_str("    /** 从指定地址读取数据 */\n");
    dts.push_str("    function read(addr: number): number;\n");
    dts.push_str("}\n\n");

    // 全局函数 (setTimeout/setInterval)
    dts.push_str("/** 延迟执行回调 (毫秒) */\n");
    dts.push_str("declare function setTimeout(callback: () => void, delayMs: number): number;\n");
    dts.push_str("/** 周期执行回调 (毫秒) */\n");
    dts.push_str("declare function setInterval(callback: () => void, intervalMs: number): number;\n");
    dts.push_str("/** 清除定时器 */\n");
    dts.push_str("declare function clearTimeout(id: number): void;\n");
    dts.push_str("/** 清除周期定时器 */\n");
    dts.push_str("declare function clearInterval(id: number): void;\n\n");

    // console
    dts.push_str("/** 控制台输出 (底层绑定 UART 串口) */\n");
    dts.push_str("declare namespace console {\n");
    dts.push_str("    function log(...args: (number | string | boolean)[]): void;\n");
    dts.push_str("    function error(...args: (number | string | boolean)[]): void;\n");
    dts.push_str("}\n\n");

    // Math
    dts.push_str("/** 数学库 (编译时静态内联) */\n");
    dts.push_str("declare namespace Math {\n");
    dts.push_str("    function max(a: number, b: number): number;\n");
    dts.push_str("    function min(a: number, b: number): number;\n");
    dts.push_str("    function abs(a: number): number;\n");
    dts.push_str("    function floor(a: number): number;\n");
    dts.push_str("    function ceil(a: number): number;\n");
    dts.push_str("    function round(a: number): number;\n");
    dts.push_str("}\n");

    dts
}

/// 生成 duanyan.json 项目配置模板
pub fn generate_project_config(project_name: &str) -> String {
    format!(
        r#"{{
    "name": "{}",
    "version": "1.0.0",
    "target": "mcu",
    "board": "counpre64-fpga",
    "entry": "src/main.js",
    "output": "dist/firmware.bin",
    "optimization": "O1"
}}"#,
        project_name
    )
}

/// 生成 Espruino 兼容 shim 的 .d.ts
pub fn generate_espruino_compat_dts() -> String {
    let mut dts = String::new();

    dts.push_str("// Espruino Compatibility Shim Type Definitions\n");
    dts.push_str("// These APIs are deprecated. Use DUANYAN standard hardware modules instead.\n\n");

    dts.push_str("/** @deprecated 使用 GPIO.output(pin) 代替 */\n");
    dts.push_str("declare function pinMode(pin: number, mode: \"input\" | \"output\"): void;\n\n");

    dts.push_str("/** @deprecated 使用 GPIO.high(pin) / GPIO.low(pin) 代替 */\n");
    dts.push_str("declare function digitalWrite(pin: number, value: boolean): void;\n\n");

    dts.push_str("/** @deprecated 使用 GPIO.read(pin) 代替 */\n");
    dts.push_str("declare function digitalRead(pin: number): boolean;\n\n");

    dts.push_str("/** @deprecated 使用 ADC.read(channel) 代替 */\n");
    dts.push_str("declare function analogRead(pin: number): number;\n\n");

    dts.push_str("/** @deprecated 使用 PWM.duty(pin, value) 代替 */\n");
    dts.push_str("declare function analogWrite(pin: number, value: number): void;\n\n");

    dts
}

